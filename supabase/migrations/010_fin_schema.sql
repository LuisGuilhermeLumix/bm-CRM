-- ---------- categorias / centros de custo ----------------------------------
create table if not exists public.fin_revenue_categories (
  id int generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
);
create table if not exists public.fin_expense_categories (
  id int generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
);
create table if not exists public.fin_cost_centers (
  id int generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
);

-- ---------- tipos de operação / sócios / regras ----------------------------
create table if not exists public.fin_operation_types (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null unique,
  color text not null default '#8b6cf6',
  active boolean not null default true,
  position int not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.fin_partners (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid null references public.profiles(id) on delete set null,
  name text not null,
  equity_pct numeric(5,2) not null default 0 check (equity_pct >= 0 and equity_pct <= 100),
  color text,
  pix_key text,
  active boolean not null default true,
  position int not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.fin_distribution_rules (
  operation_type_id uuid not null references public.fin_operation_types(id) on delete cascade,
  partner_id uuid not null references public.fin_partners(id) on delete cascade,
  pct numeric(5,2) not null default 0 check (pct >= 0 and pct <= 100),
  updated_at timestamptz not null default now(),
  primary key (operation_type_id, partner_id)
);

-- ---------- clientes ---------------------------------------------------------
create table if not exists public.fin_clients (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  contact text,
  contact_role text,
  email text,
  phone text,
  stage text not null default 'lead' check (stage in ('lead','deal','active','paused','canceled','done')),
  status text,                       -- rótulo livre legado ("Cliente ativo", "Em negociação")
  mrr numeric(12,2) not null default 0,
  since date,
  owner_id uuid null references public.profiles(id) on delete set null,
  operation_type_id uuid null references public.fin_operation_types(id) on delete set null,
  logo_bg text default '#8b6cf6',
  tags text[] not null default '{}',
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
comment on column public.fin_clients.stage is 'lead=Lead, deal=Em negociação, active=Cliente ativo, paused=Pausado, canceled=Cancelado, done=Encerrado';

-- ---------- receitas / despesas ---------------------------------------------
create table if not exists public.fin_revenues (
  id uuid primary key default gen_random_uuid(),
  client_id uuid null references public.fin_clients(id) on delete set null,
  description text not null,
  category_id int null references public.fin_revenue_categories(id) on delete set null,
  value numeric(12,2) not null,
  due_date date,
  paid_date date,
  method text,
  status text not null default 'Pendente' check (status in ('Pago','Pendente','Atrasado','Cancelado')),
  recurring boolean not null default false,
  tags text[] not null default '{}',
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.fin_expenses (
  id uuid primary key default gen_random_uuid(),
  client_id uuid null references public.fin_clients(id) on delete set null,
  description text not null,
  supplier text,                     -- fornecedor / conta (ex.: "Sicredi Credito Luis")
  category_id int null references public.fin_expense_categories(id) on delete set null,
  cost_center_id int null references public.fin_cost_centers(id) on delete set null,
  value numeric(12,2) not null,
  due_date date,
  paid_date date,
  status text not null default 'Pendente' check (status in ('Pago','Pendente','Atrasado','Cancelado')),
  tags text[] not null default '{}',
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ---------- distribuição de lucro (registros fechados por mês) --------------
create table if not exists public.fin_profit_distributions (
  id uuid primary key default gen_random_uuid(),
  month text not null unique,        -- 'YYYY-MM'
  operation_type_id uuid null references public.fin_operation_types(id) on delete set null,
  total_revenue numeric(12,2) not null default 0,
  total_expense numeric(12,2) not null default 0,
  net_amount numeric(12,2) not null default 0,
  status text not null default 'rascunho' check (status in ('rascunho','registrado')),
  registered_at timestamptz,
  registered_by uuid null references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
create table if not exists public.fin_profit_distribution_partners (
  distribution_id uuid not null references public.fin_profit_distributions(id) on delete cascade,
  partner_id uuid not null references public.fin_partners(id) on delete cascade,
  pct numeric(5,2) not null,
  amount numeric(12,2) not null,
  paid_at timestamptz,
  primary key (distribution_id, partner_id)
);

-- ---------- credenciais / anotações ------------------------------------------
create table if not exists public.fin_credentials (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  service text,
  client_id uuid null references public.fin_clients(id) on delete set null,
  login text,
  secret_encrypted text,
  secret_iv text,
  url text,
  access text not null default 'editor',
  owner_id uuid null references public.profiles(id) on delete set null,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
comment on column public.fin_credentials.secret_encrypted is 'Segredo cifrado no cliente (AES-GCM). Nunca gravar em texto puro.';

create table if not exists public.fin_notes (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  body text not null default '',
  tags text[] not null default '{}',
  favorite boolean not null default false,
  author_id uuid null references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ---------- índices ----------------------------------------------------------
create index if not exists fin_revenues_due_idx   on public.fin_revenues (due_date);
create index if not exists fin_revenues_paid_idx  on public.fin_revenues (paid_date);
create index if not exists fin_revenues_client_idx on public.fin_revenues (client_id);
create index if not exists fin_expenses_due_idx   on public.fin_expenses (due_date);
create index if not exists fin_expenses_paid_idx  on public.fin_expenses (paid_date);
create index if not exists fin_expenses_client_idx on public.fin_expenses (client_id);
create index if not exists fin_clients_stage_idx  on public.fin_clients (stage);

-- ---------- updated_at -------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['fin_operation_types','fin_clients','fin_revenues','fin_expenses','fin_credentials','fin_notes'] loop
    execute format('drop trigger if exists %I on public.%I', t || '_set_updated_at', t);
    execute format('create trigger %I before update on public.%I for each row execute function public.set_updated_at()', t || '_set_updated_at', t);
  end loop;
end $$;

-- ---------- RLS: só quem está liberado no BM (profiles.allowed) -------------
do $$
declare t text;
begin
  foreach t in array array[
    'fin_revenue_categories','fin_expense_categories','fin_cost_centers',
    'fin_operation_types','fin_partners','fin_distribution_rules',
    'fin_clients','fin_revenues','fin_expenses',
    'fin_profit_distributions','fin_profit_distribution_partners',
    'fin_credentials','fin_notes'
  ] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_all_allowed', t);
    execute format(
      'create policy %I on public.%I for all to authenticated using (public.crm_allowed()) with check (public.crm_allowed())',
      t || '_all_allowed', t);
  end loop;
end $$;

-- ---------- realtime ---------------------------------------------------------
do $$
declare t text;
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    foreach t in array array['fin_clients','fin_revenues','fin_expenses'] loop
      if not exists (select 1 from pg_publication_tables
                      where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = t) then
        execute format('alter publication supabase_realtime add table public.%I', t);
      end if;
    end loop;
  end if;
end $$;
