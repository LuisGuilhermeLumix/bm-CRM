-- Lumix BM — 010: schema do Financeiro (prefixo fin_)
-- Espelha o schema do projeto antigo "lumixgeral" (clients, revenues,
-- expenses, partners, operation_types, distribution_rules, profit_distributions,
-- credentials, notes) para dentro do projeto SDR, sem tocar em nenhuma tabela
